use serde::{Deserialize, Serialize};
use std::fs;
use std::path::PathBuf;

#[derive(Serialize, Deserialize, Debug, Clone)]
pub struct ExportScriptRow {
    pub entryorguid: i64,
    pub source_type: u8,
    pub id: u16,
    pub link: u16,
    pub event_type: u8,
    pub event_phase_mask: u8,
    pub event_chance: u8,
    pub event_flags: u16,
    pub event_param1: u32,
    pub event_param2: u32,
    pub event_param3: u32,
    pub event_param4: u32,
    pub event_param5: u32,
    pub event_param_string: String,
    pub action_type: u8,
    pub action_param1: u32,
    pub action_param2: u32,
    pub action_param3: u32,
    pub action_param4: u32,
    pub action_param5: u32,
    pub action_param6: u32,
    pub target_type: u8,
    pub target_param1: u32,
    pub target_param2: u32,
    pub target_param3: u32,
    pub target_x: f32,
    pub target_y: f32,
    pub target_z: f32,
    pub target_o: f32,
    pub comment: String,
}

#[derive(Serialize, Deserialize, Debug, Clone)]
#[serde(rename_all = "PascalCase")]
pub struct ExportConditionRow {
    pub source_type_or_reference_id: i32,
    pub source_group: u32,
    pub source_entry: i32,
    pub source_id: u32,
    pub else_group: u32,
    pub condition_type_or_reference: i32,
    pub condition_target: u8,
    pub condition_value1: u32,
    pub condition_value2: u32,
    pub condition_value3: u32,
    pub negative_condition: bool,
    pub error_type: u32,
    pub error_text_id: u32,
    pub script_name: String,
}

#[tauri::command]
pub async fn export_scripts_sql(rows: Vec<ExportScriptRow>, conditions: Vec<ExportConditionRow>) -> Result<String, String> {
    let mut sql = String::new();
    sql.push_str("-- FluxSAI SQL Export\n");
    sql.push_str("-- Generated by FluxSAI SmartAI Editor\n\n");

    for row in rows {
        sql.push_str(&format!(
            "DELETE FROM `smart_scripts` WHERE `entryorguid` = {} AND `source_type` = {} AND `id` = {};\n",
            row.entryorguid, row.source_type, row.id
        ));
        sql.push_str(&format!(
            "INSERT INTO `smart_scripts` (`entryorguid`, `source_type`, `id`, `link`, `event_type`, `event_phase_mask`, \
`event_chance`, `event_flags`, `event_param1`, `event_param2`, `event_param3`, `event_param4`, `event_param5`, \
`event_param_string`, `action_type`, `action_param1`, `action_param2`, `action_param3`, `action_param4`, \
`action_param5`, `action_param6`, `target_type`, `target_param1`, `target_param2`, `target_param3`, \
`target_x`, `target_y`, `target_z`, `target_o`, `comment`) VALUES\n"
        ));
        sql.push_str(&format!(
            "({}, {}, {}, {}, {}, {}, {}, {}, {}, {}, {}, {}, {}, '{}', {}, {}, {}, {}, {}, {}, {}, {}, {}, {}, {}, {}, {}, {}, {}, '{}');\n\n",
            row.entryorguid, row.source_type, row.id, row.link,
            row.event_type, row.event_phase_mask, row.event_chance, row.event_flags,
            row.event_param1, row.event_param2, row.event_param3, row.event_param4, row.event_param5,
            row.event_param_string.replace('\'', "''"),
            row.action_type, row.action_param1, row.action_param2, row.action_param3,
            row.action_param4, row.action_param5, row.action_param6,
            row.target_type, row.target_param1, row.target_param2, row.target_param3,
            row.target_x, row.target_y, row.target_z, row.target_o,
            row.comment.replace('\'', "''")
        ));
    }

    if !conditions.is_empty() {
        sql.push_str("\n-- Conditions\n\n");
        for cond in conditions {
            sql.push_str(&format!(
                "DELETE FROM `conditions` WHERE `SourceTypeOrReferenceId` = {} AND `SourceGroup` = {} AND `SourceEntry` = {} AND `SourceId` = {} AND `ElseGroup` = {} AND `ConditionTypeOrReference` = {} AND `ConditionTarget` = {};\n",
                cond.source_type_or_reference_id, cond.source_group, cond.source_entry, cond.source_id,
                cond.else_group, cond.condition_type_or_reference, cond.condition_target
            ));
            sql.push_str(&format!(
                "INSERT INTO `conditions` (`SourceTypeOrReferenceId`, `SourceGroup`, `SourceEntry`, `SourceId`, `ElseGroup`, `ConditionTypeOrReference`, `ConditionTarget`, `ConditionValue1`, `ConditionValue2`, `ConditionValue3`, `NegativeCondition`, `ErrorType`, `ErrorTextId`, `ScriptName`) VALUES\n"
            ));
            sql.push_str(&format!(
                "({}, {}, {}, {}, {}, {}, {}, {}, {}, {}, {}, {}, {}, '{}');\n\n",
                cond.source_type_or_reference_id, cond.source_group, cond.source_entry, cond.source_id,
                cond.else_group, cond.condition_type_or_reference, cond.condition_target,
                cond.condition_value1, cond.condition_value2, cond.condition_value3,
                cond.negative_condition as u8, cond.error_type, cond.error_text_id,
                cond.script_name.replace('\'', "''")
            ));
        }
    }

    Ok(sql)
}

#[tauri::command]
pub async fn save_entry_to_file(rows: Vec<ExportScriptRow>, conditions: Vec<ExportConditionRow>) -> Result<String, String> {
    if rows.is_empty() {
        return Err("No rows to save".to_string());
    }

    let entry = rows[0].entryorguid;
    let source_type = rows[0].source_type;

    let exe_dir = std::env::current_exe()
        .map_err(|e| format!("Cannot find exe path: {}", e))?;
    let exe_dir = exe_dir.parent()
        .ok_or_else(|| "Cannot find exe directory".to_string())?
        .to_path_buf();

    let scripts_dir: PathBuf = exe_dir.join("FluxSAI Scripts");
    fs::create_dir_all(&scripts_dir)
        .map_err(|e| format!("Cannot create directory: {}", e))?;

    let filename = format!("entry_{}_type_{}.sql", entry, source_type);
    let filepath = scripts_dir.join(&filename);

    let mut sql = String::new();
    sql.push_str("-- FluxSAI Script Export\n");
    sql.push_str(&format!("-- Entry: {}, Source Type: {}\n\n", entry, source_type));

    sql.push_str(&format!(
        "DELETE FROM `smart_scripts` WHERE `entryorguid` = {} AND `source_type` = {};\n\n",
        entry, source_type
    ));

    for row in &rows {
        sql.push_str(&format!(
            "INSERT INTO `smart_scripts` (`entryorguid`, `source_type`, `id`, `link`, `event_type`, `event_phase_mask`, \
`event_chance`, `event_flags`, `event_param1`, `event_param2`, `event_param3`, `event_param4`, `event_param5`, \
`event_param_string`, `action_type`, `action_param1`, `action_param2`, `action_param3`, `action_param4`, \
`action_param5`, `action_param6`, `target_type`, `target_param1`, `target_param2`, `target_param3`, \
`target_x`, `target_y`, `target_z`, `target_o`, `comment`) VALUES\n"
        ));
        sql.push_str(&format!(
            "({}, {}, {}, {}, {}, {}, {}, {}, {}, {}, {}, {}, {}, '{}', {}, {}, {}, {}, {}, {}, {}, {}, {}, {}, {}, {}, {}, {}, {}, '{}');\n\n",
            row.entryorguid, row.source_type, row.id, row.link,
            row.event_type, row.event_phase_mask, row.event_chance, row.event_flags,
            row.event_param1, row.event_param2, row.event_param3, row.event_param4, row.event_param5,
            row.event_param_string.replace('\'', "''"),
            row.action_type, row.action_param1, row.action_param2, row.action_param3,
            row.action_param4, row.action_param5, row.action_param6,
            row.target_type, row.target_param1, row.target_param2, row.target_param3,
            row.target_x, row.target_y, row.target_z, row.target_o,
            row.comment.replace('\'', "''")
        ));
    }

    if !conditions.is_empty() {
        sql.push_str("-- Conditions\n\n");
        if let Some(first_cond) = conditions.first() {
            sql.push_str(&format!(
                "DELETE FROM `conditions` WHERE `SourceTypeOrReferenceId` = 22 AND `SourceEntry` = {} AND `SourceId` = {};\n\n",
                first_cond.source_entry, first_cond.source_id
            ));
        }
        for cond in &conditions {
            sql.push_str(&format!(
                "INSERT INTO `conditions` (`SourceTypeOrReferenceId`, `SourceGroup`, `SourceEntry`, `SourceId`, `ElseGroup`, `ConditionTypeOrReference`, `ConditionTarget`, `ConditionValue1`, `ConditionValue2`, `ConditionValue3`, `NegativeCondition`, `ErrorType`, `ErrorTextId`, `ScriptName`) VALUES\n"
            ));
            sql.push_str(&format!(
                "({}, {}, {}, {}, {}, {}, {}, {}, {}, {}, {}, {}, {}, '{}');\n\n",
                cond.source_type_or_reference_id, cond.source_group, cond.source_entry, cond.source_id,
                cond.else_group, cond.condition_type_or_reference, cond.condition_target,
                cond.condition_value1, cond.condition_value2, cond.condition_value3,
                cond.negative_condition as u8, cond.error_type, cond.error_text_id,
                cond.script_name.replace('\'', "''")
            ));
        }
    }

    fs::write(&filepath, sql)
        .map_err(|e| format!("Cannot write file: {}", e))?;

    Ok(format!("Saved to FluxSAI Scripts/{}", filename))
}
